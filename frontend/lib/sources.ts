export type SourceId = (typeof SOURCE_IDS)[number];

export const SOURCE_KINDS = ["api", "feed", "curated", "link", "student", "ai"] as const;

export type SourceKind = (typeof SOURCE_KINDS)[number];

export interface SourceInfo {
  id: SourceId;
  /** Exact tag text, upper case ("YOUR PLAN"). Always `label.toUpperCase()`. */
  tag: string;
  /** Name in normal case ("Your plan"): what SourceTag and the Sources panel render. */
  label: string;
  kind: SourceKind;
  /** Public home page of the source; null for student-entered and AI data. */
  url: string | null;
  /** Reserved ids are defined but must not be used yet (see `course-site`). */
  reserved?: true;
}

function source(
  id: SourceId,
  label: string,
  kind: SourceKind,
  url: string | null,
  extra: Pick<SourceInfo, "reserved"> = {},
): SourceInfo {
  return { id, tag: label.toUpperCase(), label, kind, url, ...extra };
}

