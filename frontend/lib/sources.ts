/**
 * Where aggregated items come from (PLAN §4.1.13, §5 "Sources (truthfulness)"). Every aggregated item stores one
 * of these ids in its `source` field and renders it with `<SourceTag source>`: a small uppercase tag
 * (Broadsheet idea adopted for Lakeside: WILDCATSYNC, HANDSHAKE, DAVIDSON ONE, YOUR PLAN, ...).
 *
 * - `label` is the name in normal case. SourceTag and the Sources panel render it; the tag uppercases it with CSS
 *   so screen readers read words, not letters.
 * - `tag` is exactly what the tag shows (`label` in upper case). Use it in plain-text contexts (print view,
 *   "Copy for WebTree", tests); never build tag text any other way.
 * - `kind` says how MakeItSo gets the data, which decides where the Sources panel lists it:
 *     api      synced from an upstream API (last-sync time shown)
 *     feed     synced from an ICS/RSS/JSON feed (last-sync time shown)
 *     curated  hand-checked content with a `verifiedAt` date ("verified <date>")
 *     link     a platform MakeItSo only links to (listed under "Links"; HANDSHAKE / DAVIDSON ONE tags appear
 *              only on these curated deep links)
 *     student  entered by the student in MakeItSo
 *     ai       generated by MakeItSo's AI features (always shown with the "AI · verify with your advisor" chip)
 * - `url` is the public home of the source (null for student/AI data).
 *
 * `course-site` (Moodle) is reserved: nothing may use it until T&I approves (PLAN §1).
 */

