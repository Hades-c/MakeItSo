/** Sources MakeItSo syncs itself (kind api or feed): the only ids `fetchExternal` and `recordSync` accept. */
export const SYNCED_SOURCE_IDS = [
  "course-schedule",
  "catalog",
  "ratemyprofessors",
  "wildcatsync",
  "hurt-hub",
  "library",
  "davidsonian",
  "events-digest",
  "davidson-news",
] as const satisfies readonly SourceId[];

export type SyncedSourceId = (typeof SYNCED_SOURCE_IDS)[number];

export function isSourceId(value: unknown): value is SourceId {
  return typeof value === "string" && (SOURCE_IDS as readonly string[]).includes(value);
}

export function isSyncedSourceId(value: unknown): value is SyncedSourceId {
  return typeof value === "string" && (SYNCED_SOURCE_IDS as readonly string[]).includes(value);
}

export function sourceLabel(id: SourceId): string {
  return SOURCES[id].label;
}

/** The exact uppercase tag text for plain-text contexts ("WILDCATSYNC"). */
export function sourceTag(id: SourceId): string {
  return SOURCES[id].tag;
}

/** Every non-reserved source of one kind, in registry order. */
export function sourcesOfKind(kind: SourceKind): SourceInfo[] {
  return SOURCE_IDS.map((id) => SOURCES[id]).filter((s) => s.kind === kind && !s.reserved);
}
