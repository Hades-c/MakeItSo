async function teacher(first: string, last: string, legacyId: number, numRatings: number) {
  await RmpTeacher.create({
    rmpId: `VGVhY2hlci0${legacyId}`,
    legacyId,
    firstName: first,
    lastName: last,
    normalizedFirst: normalizeName(first),
    normalizedLast: normalizeName(last),
    nameTokens: indexTokens(first, last),
    department: "Computer Science",
    schoolId: RMP_DAVIDSON_SCHOOL_ID,
    avgRating: 4.2,
    avgDifficulty: 3.1,
    numRatings,
    wouldTakeAgainPct: 80,
    fetchedAt: new Date("2026-09-28T00:00:00Z"),
  });
}

async function signIn() {
  const user = await insertStudent();
  auth.session = await sessionFor(user);
  return user;
}

const INSTRUCTOR = { first: "Katy", last: "Williams", isStaff: false };
const post = (body: unknown) => route.POST(aiRequest("/api/ai/professor-summary", body));
const ask = (instructor = INSTRUCTOR, courseCode = "CSC 221") =>
  post({ termCode: "202602", courseCode, instructor });

describe("with RMP_SUMMARIES_ENABLED off (the default) nothing runs", () => {
  it("the route answers disabled before reading anything", async () => {
    expect(isDefinedRoute(route.POST)).toBe(true);
    expect(route.maxDuration).toBe(120);
    await signIn();
    const res = await ask();
    expect(res.status).toBe(404);
    expect(await bodyOf(res)).toEqual({ kind: "disabled", message: "AI features are turned off." });
  });

  it("the weekly job skips without reading the catalog, the roster or any review", async () => {
    const fetchReviews = vi.fn(async () => reviews(6));
    expect(await runProfessorSummaryJob({ fetchReviews })).toEqual({
      skipped: "disabled",
      profiles: 0,
      generated: 0,
      fresh: 0,
      failed: 0,
      stoppedEarly: null,
    });
    expect(fetchReviews).not.toHaveBeenCalled();
    vi.stubEnv("CRON_SECRET", CRON_SECRET);
    const res = await cronRoute.GET(
      new Request("http://localhost/api/cron/ai/professor-summaries", {
        headers: { authorization: `Bearer ${CRON_SECRET}` },
      }),
    );
    expect(res.status).toBe(200);
    expect(await res.json()).toMatchObject({ skipped: "disabled" });
    expect(mockAiRequests()).toHaveLength(0);
  });
});

describe("with RMP_SUMMARIES_ENABLED on", () => {
  beforeEach(() => {
    vi.stubEnv("RMP_SUMMARIES_ENABLED", "true");
  });

  it("the weekly job writes shared summaries for matched profiles with 5+ ratings, never storing review text", async () => {
    await teacher("Katy", "Williams", 111, 12);
    const fetchReviews = vi.fn(async () => reviews(8));
    const result = await runProfessorSummaryJob({ fetchReviews });
    expect(result).toMatchObject({
      skipped: null,
      profiles: 1,
      generated: 1,
      failed: 0,
      stoppedEarly: null,
    });
    expect(fetchReviews).toHaveBeenCalledWith(111);

    const stored = await AiCache.find({ feature: "professor-summary" }).lean();
    expect(stored).toHaveLength(1);
    expect(stored[0]).toMatchObject({ scope: "shared", key: "rmp:111", status: "ok" });
    const everything = JSON.stringify([stored, await AiUsage.find().lean()]);
    expect(everything).not.toContain("SYNTHETIC-REVIEW");
    // The reviews reached the model as untrusted data.
    expect(JSON.stringify(mockAiRequests()[0]!.params.messages)).toContain("untrusted_reviews");

    expect(await runProfessorSummaryJob({ fetchReviews })).toMatchObject({
      generated: 0,
      fresh: 1,
    });
    expect(fetchReviews).toHaveBeenCalledTimes(1);
  });

  it("the route reads the weekly entry (it never generates)", async () => {
    await teacher("Katy", "Williams", 111, 12);
    await signIn();
    const before = await ask();
    expect(before.status).toBe(503);
    expect(await bodyOf(before)).toEqual({ kind: "unavailable", message: SUMMARY_NOT_AVAILABLE });
    expect(mockAiRequests()).toHaveLength(0);

    await runProfessorSummaryJob({ fetchReviews: async () => reviews(6) });
    const res = await ask();
    expect(res.status).toBe(200);
    const body = ProfessorSummaryResultSchema.parse(await bodyOf(res));
    expect(body).toMatchObject({
      kind: "ok",
      cached: true,
      data: { provenance: { promptVersion: "professor-summary/1" } },
    });
    if (body.kind === "ok") expect(JSON.stringify(body.data.summary)).not.toMatch(/Katy|Williams/);
  });

  it("needs a matched profile with at least 5 ratings, and an instructor of that course", async () => {
    await teacher("Katy", "Williams", 111, 4);
    await signIn();
    expect(await bodyOf(await ask())).toEqual({ kind: "unavailable", message: TOO_FEW_RATINGS });
    const course = await getCourse("202602", "CSC 121");
    const other = course!.sections[0]!.instructors[0]!;
    const unmatched = await ask(other, "CSC 121");
    expect(await bodyOf(unmatched)).toEqual({ kind: "unavailable", message: NOT_MATCHED });
    const wrong = await ask({ first: "Nobody", last: "Atall", isStaff: false });
    expect(wrong.status).toBe(404);
    expect((await errorOf(wrong)).code).toBe("not_found");
    expect(await runProfessorSummaryJob({ fetchReviews: async () => reviews(6) })).toMatchObject({
      profiles: 0,
    });
  });

  it("rejects summaries that quote or copy reviews (remembered for a day), and skips profiles whose reviews fail", async () => {
    await teacher("Katy", "Williams", 111, 12);
    setMockAiScenario("quote_reviews", { times: 1 });
    const quoted = await runProfessorSummaryJob({ fetchReviews: async () => reviews(6) });
    expect(quoted).toMatchObject({ generated: 0, failed: 1 });
    expect(await AiCache.findOne({ key: "rmp:111" }).lean()).toMatchObject({
      status: "invalid",
      data: null,
    });

    await AiCache.deleteMany({});
    vi.spyOn(console, "error").mockImplementation(() => undefined);
    const down = await runProfessorSummaryJob({
      fetchReviews: async () => {
        throw new ExternalFetchError(
          "ratemyprofessors",
          "https://www.ratemyprofessors.com/graphql",
          "timeout",
          "x",
        );
      },
    });
    expect(down).toMatchObject({ generated: 0, failed: 1 });
    const few = await runProfessorSummaryJob({ fetchReviews: async () => reviews(3) });
    expect(few).toMatchObject({ generated: 0, failed: 1 });
    await expect(
      runProfessorSummaryJob({
        fetchReviews: async () => {
          throw new TypeError("a bug");
        },
      }),
    ).rejects.toThrow("a bug");
  });

  it("stops at the time budget", async () => {
    await teacher("Katy", "Williams", 111, 12);
    expect(
      await runProfessorSummaryJob({ timeBudgetMs: -1, fetchReviews: async () => reviews(6) }),
    ).toMatchObject({
      stoppedEarly: "deadline",
      generated: 0,
    });
  });
});

describe("cleanProfessorSummary", () => {
  const context = { names: ["Katy", "Williams"], reviews: [] as string[] };

  it("replaces the instructor's name and cleans the text", () => {
    expect(
      cleanProfessorSummary(
        {
          summary:
            "Reviewers say Prof. Katy Williams explains clearly; Williams is patient. See https://x.example",
          themes: ["Williams's drawings", "Patience"],
        },
        context,
      ),
    ).toEqual({
      summary: "Reviewers say the professor explains clearly; the professor is patient. See",
      themes: ["the professor's drawings", "Patience"],
    });
  });

  it("rejects long quotations and long copied runs", () => {
    const review =
      "one two three four five six seven eight nine ten eleven twelve thirteen fourteen fifteen sixteen seventeen eighteen nineteen twenty twentyone";
    expect(
      cleanProfessorSummary({ summary: `They wrote "${review}"`, themes: [] }, context),
    ).toBeNull();
    expect(
      cleanProfessorSummary(
        { summary: `Reviewers: ${review}.`, themes: [] },
        { ...context, reviews: [review] },
      ),
    ).toBeNull();
    expect(cleanProfessorSummary({ summary: "Too short.", themes: [] }, context)).toBeNull();
  });
});

